def classify_risk(depth):

    if depth < 0.30:
        return "LOW"

    elif depth < 0.75:
        return "MODERATE"

    elif depth < 1.50:
        return "HIGH"

    return "SEVERE"


def warning_message(depth):

    if depth < 0.30:
        return "No significant flooding expected."

    elif depth < 0.75:
        return "Localized shallow flooding may occur."

    elif depth < 1.50:
        return "Flooding may affect roads and low-lying areas."

    return "Significant flooding likely. Immediate monitoring advised."

def predict_flood_depth(
    rainfall_24h,
    state
):

    rainfall_24h = np.array(
        rainfall_24h,
        dtype=float
    )

    if len(rainfall_24h) != 24:
        raise ValueError(
            "Exactly 24 rainfall values required."
        )

    window = np.column_stack([

        rainfall_24h,

        np.full(
            24,
            state["up_depth"]
        ),

        np.full(
            24,
            state["up_vel"]
        ),

        np.full(
            24,
            state["bridge_vel"]
        ),

        np.full(
            24,
            state["bridge_depth"]
        )

    ])

    window_scaled = x_scaler.transform(
        window.reshape(-1,5)
    ).reshape(1,24,5)

    pred_scaled = model.predict(
        window_scaled,
        verbose=0
    )

    pred_depth = y_scaler.inverse_transform(
        pred_scaled
    )[0,0]

    risk = classify_risk(
        pred_depth
    )

    return pred_depth, risk

from datetime import timedelta

def predict_flood_series(
    rainfall_values,
    start_datetime,
    state
):

    rainfall_values = np.array(
        rainfall_values,
        dtype=float
    )

    predictions = []

    forecast_times = []

    for i in range(
        len(rainfall_values) - 24 + 1
    ):

        rain_window = rainfall_values[
            i:i+24
        ]

        pred_depth, _ = predict_flood_depth(
            rain_window,
            state
        )

        predictions.append(
            pred_depth
        )

        forecast_times.append(
            start_datetime
            + timedelta(hours=i+24)
        )

    return (
        forecast_times,
        np.array(predictions)
    )

