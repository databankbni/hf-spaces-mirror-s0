def interpret_case_metrics(
    rmse,
    mae,
    r2,
    nse
):

    interpretation = []

    if rmse < 0.05:
        interpretation.append(
            "RMSE indicates very low prediction error."
        )
    else:
        interpretation.append(
            "RMSE indicates moderate prediction error."
        )

    interpretation.append(
        f"Average prediction error is approximately {mae*100:.2f} cm."
    )

    if r2 >= 0.90:
        interpretation.append(
            f"The model explains {r2*100:.2f}% of the observed variance, indicating an excellent fit."
        )
    elif r2 >= 0.75:
        interpretation.append(
            f"The model explains {r2*100:.2f}% of the observed variance, indicating a good fit."
        )
    else:
        interpretation.append(
            f"The model explains {r2*100:.2f}% of the observed variance."
        )

    if nse >= 0.75:
        interpretation.append(
            "NSE indicates excellent predictive performance."
        )
    elif nse >= 0.50:
        interpretation.append(
            "NSE indicates acceptable predictive performance."
        )
    else:
        interpretation.append(
            "NSE indicates limited predictive performance."
        )

    return "\n\n".join(
        interpretation
    )

